@app.on_message(filters.text)
async def chat_with_gpt(client, message):

    # Не обрабатываем команды
    if message.text.startswith("/"):
        return
    menu_buttons = {
        "Что я умею",
        "Как забронировать",
        "Идеи для отдыха",
        "Заявка менеджеру"
    }
    
    if message.text in menu_buttons:
        return
    user_id = message.from_user.id

    print("====================================")
    print(
        "📩 ПОЛУЧЕНО СООБЩЕНИЕ:",
        message.text,
        flush=True
    )
    print(
        "👤 USER ID:",
        user_id,
        flush=True
    )
    print("====================================")

    try:

        print(
            "➡️ Передаю сообщение в ask_gpt()",
            flush=True
        )

        answer, need_manager = await asyncio.to_thread(
            ask_gpt,
            user_id,
            message.text
        )
        
        if need_manager:
            await message.reply(
                answer,
                reply_markup=manager_keyboard
            )
        else:
            await message.reply(answer)

        print(
            "📤 Ответ отправлен пользователю",
            flush=True
        )

    except Exception as e:

        print("====================================")
        print("💥 ОШИБКА ОБРАБОТЧИКА")
        print("====================================")

        print(
            "Класс:",
            type(e).__name__,
            flush=True
        )

        print(
            "Ошибка:",
            str(e),
            flush=True
        )

        print("====================================")

        await message.reply(
            "😔 Произошла ошибка при обращении к AI.\n\n"
            "Попробуй ещё раз."
        )


